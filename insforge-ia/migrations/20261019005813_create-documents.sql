-- Extensão para busca por similaridade vetorial
CREATE EXTENSION IF NOT EXISTS vector;

-- Documentos que a IA poderá consultar
CREATE TABLE IF NOT EXISTS public.documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    content text NOT NULL,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_published boolean NOT NULL DEFAULT false,
    embedding vector(1536),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- Índice para acelerar a busca semântica
CREATE INDEX IF NOT EXISTS documents_embedding_hnsw_idx
ON public.documents
USING hnsw (embedding vector_cosine_ops)
WHERE embedding IS NOT NULL;

-- Impede acesso direto aos documentos pela API pública
ALTER TABLE public.documents ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE public.documents
FROM PUBLIC, anon, authenticated;

-- Busca apenas documentos publicados
CREATE OR REPLACE FUNCTION public.match_documents(
    query_embedding vector(1536),
    match_threshold double precision DEFAULT 0.50,
    match_count integer DEFAULT 5
)
RETURNS TABLE (
    id bigint,
    title text,
    content text,
    metadata jsonb,
    similarity double precision
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
    SELECT
        d.id,
        d.title,
        d.content,
        d.metadata,
        (1 - (d.embedding <=> query_embedding))::double precision
            AS similarity
    FROM public.documents AS d
    WHERE d.is_published = true
      AND d.embedding IS NOT NULL
      AND (1 - (d.embedding <=> query_embedding)) >= match_threshold
    ORDER BY d.embedding <=> query_embedding
    LIMIT LEAST(GREATEST(COALESCE(match_count, 5), 1), 10);
$$;

-- A função pode ser usada para consultar documentos publicad
REVOKE ALL ON FUNCTION public.match_documents(vector, double precision, integer)
FROM PUBLIC;

GRANT EXECUTE ON FUNCTION public.match_documents(vector, double precision, integer)
TO anon, authenticated;